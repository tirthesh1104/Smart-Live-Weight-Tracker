import React, { useState } from 'react';
import { 
  Train, 
  Coach, 
  PassengerSubmission, 
  SeatBerth 
} from '../../types';
import { CoachLayoutService } from '../../services/coachLayoutService';
import { OfflineStorageService } from '../../services/offlineStorage';
import { CoachSelectionHeader } from './CoachSelectionHeader';
import { CoachVisualLayout } from './CoachVisualLayout';
import { 
  CheckCircle2, 
  XCircle, 
  FileSpreadsheet, 
  Printer, 
  Users, 
  ShieldCheck, 
  AlertTriangle,
  ClipboardCheck,
  Search
} from 'lucide-react';

interface StaffCoachSeatManagerProps {
  trains: Train[];
  staffName?: string;
}

export const StaffCoachSeatManager: React.FC<StaffCoachSeatManagerProps> = ({
  trains,
  staffName = 'Station Duty Staff'
}) => {
  const [selectedTrain, setSelectedTrain] = useState<Train>(trains[0] || {} as Train);
  const [selectedCoachId, setSelectedCoachId] = useState<string>(
    trains[0]?.coaches[0]?.id || ''
  );
  const [journeyDate, setJourneyDate] = useState<string>(new Date().toISOString().slice(0, 10));
  const [submissions, setSubmissions] = useState<PassengerSubmission[]>(() => {
    return CoachLayoutService.getPassengerSubmissions();
  });

  const activeCoach = selectedTrain?.coaches.find(c => c.id === selectedCoachId) || selectedTrain?.coaches[0];

  const refreshSubmissions = () => {
    setSubmissions(CoachLayoutService.getPassengerSubmissions());
  };

  const handleVerifySubmission = (subId: string) => {
    CoachLayoutService.updateSubmissionState(
      subId,
      'Verified',
      `Physical presence confirmed by ${staffName} on platform chart check.`,
      staffName
    );
    refreshSubmissions();
  };

  const handleRejectSubmission = (subId: string) => {
    const reason = window.prompt('Enter reason for rejecting check-in (e.g. Passenger not present at designated berth):');
    if (reason !== null) {
      CoachLayoutService.updateSubmissionState(
        subId,
        'Rejected',
        reason || 'Discrepancy detected during physical charting check.',
        staffName
      );
      refreshSubmissions();
    }
  };

  // Export Manifest CSV
  const handleExportManifest = () => {
    if (!activeCoach) return;
    const seats = CoachLayoutService.getCoachSeats(activeCoach, selectedTrain);
    let csv = `COACH OPERATIONAL MANIFEST: TRAIN #${selectedTrain.number} ${selectedTrain.name} - COACH ${activeCoach.coach_no}\n`;
    csv += `Class: ${activeCoach.coach_type} | Generated by: ${staffName} | Timestamp: ${new Date().toISOString()}\n\n`;
    csv += "Seat No,Berth Type,Booking Status,Physical Occupancy,Passenger Name,PNR Masked,From,To\n";

    seats.forEach(s => {
      csv += `${s.seat_number},"${s.berth_type}","${s.booking_status}","${s.physical_status}","${s.passenger_name_masked || 'N/A'}","${s.pnr_masked || 'N/A'}","${s.journey_from}","${s.journey_to}"\n`;
    });

    const blob = new Blob([csv], { type: 'text/csv;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `Manifest_Train_${selectedTrain.number}_Coach_${activeCoach.coach_no}_${journeyDate}.csv`;
    a.click();
    URL.revokeObjectURL(url);
    OfflineStorageService.addAuditLog('Coach Manifest Exported', {
      trainNumber: selectedTrain.number,
      coachNo: activeCoach.coach_no,
      staffName
    });
  };

  // Filter pending submissions for active train
  const pendingSubmissions = submissions.filter(
    s => s.train_number === selectedTrain.number && s.verification_state !== 'Verified'
  );

  return (
    <div className="space-y-4">
      
      {/* 1. Header Banner & Operational Manifest Toolbar */}
      <div className="gov-card p-4 flex flex-col md:flex-row md:items-center justify-between gap-3 border-t-4 border-t-[#003366] dark:border-t-blue-500">
        <div className="flex items-center gap-3">
          <div className="w-10 h-10 rounded-sm bg-blue-50 dark:bg-blue-950/60 border border-blue-200 dark:border-blue-800 text-[#003366] dark:text-blue-300 flex items-center justify-center shrink-0">
            <ClipboardCheck className="w-5 h-5" />
          </div>
          <div>
            <h2 className="text-sm sm:text-base font-bold text-[#002244] dark:text-blue-100 uppercase tracking-tight">
              Railway Staff Coach &amp; Berth Charting Desk
            </h2>
            <p className="text-xs text-slate-600 dark:text-slate-400">
              Station Superintendent / TTE on-board physical verification and passenger check-in reconciliation.
            </p>
          </div>
        </div>

        <div className="flex items-center gap-2">
          <button
            onClick={handleExportManifest}
            className="px-3 py-1.5 bg-emerald-50 hover:bg-emerald-100 dark:bg-emerald-950/60 dark:hover:bg-emerald-900 text-emerald-800 dark:text-emerald-200 border border-emerald-300 dark:border-emerald-800 text-xs font-bold rounded-sm flex items-center gap-1.5 cursor-pointer transition shadow-xs"
            title="Download Operational Passenger Manifest (CSV / Excel)"
          >
            <FileSpreadsheet className="w-3.5 h-3.5 text-emerald-700 dark:text-emerald-400" />
            <span>Export Coach Manifest</span>
          </button>
          <button
            onClick={() => window.print()}
            className="px-3 py-1.5 bg-blue-50 hover:bg-blue-100 dark:bg-blue-950/60 dark:hover:bg-blue-900 text-blue-800 dark:text-blue-200 border border-blue-300 dark:border-blue-800 text-xs font-bold rounded-sm flex items-center gap-1.5 cursor-pointer transition shadow-xs"
            title="Print Coach Chart"
          >
            <Printer className="w-3.5 h-3.5 text-blue-700 dark:text-blue-400" />
            <span>Print Chart</span>
          </button>
        </div>
      </div>

      {/* 2. Train & Coach Selector */}
      {selectedTrain && (
        <CoachSelectionHeader
          train={selectedTrain}
          trainsList={trains}
          onSelectTrain={(t) => {
            setSelectedTrain(t);
            setSelectedCoachId(t.coaches[0]?.id || '');
          }}
          selectedCoachId={selectedCoachId}
          onSelectCoach={(c) => setSelectedCoachId(c.id)}
          journeyDate={journeyDate}
          onDateChange={setJourneyDate}
        />
      )}

      {/* 3. Interactive Coach Interior Layout (Staff mode allows physical check recording) */}
      {activeCoach && selectedTrain && (
        <CoachVisualLayout
          coach={activeCoach}
          train={selectedTrain}
          viewerRole="staff"
        />
      )}

      {/* 4. On-Board Passenger Verification Queue */}
      <div className="gov-card overflow-hidden">
        <div className="p-3.5 bg-slate-50 dark:bg-slate-800/80 border-b border-slate-200 dark:border-slate-700 flex items-center justify-between">
          <div className="flex items-center gap-2">
            <ShieldCheck className="w-4 h-4 text-[#003366] dark:text-blue-400" />
            <h3 className="text-xs font-bold uppercase tracking-wider text-[#002244] dark:text-blue-200">
              Passenger Self-Reported Check-in Queue &bull; Train #{selectedTrain?.number} ({pendingSubmissions.length} Pending)
            </h3>
          </div>
          <span className="text-[11px] text-slate-500">
            Click to confirm physical passenger presence
          </span>
        </div>

        <div className="overflow-x-auto">
          <table className="gov-table">
            <thead>
              <tr>
                <th className="w-24">Coach / Berth</th>
                <th>Passenger Name</th>
                <th className="w-32">PNR Reference</th>
                <th>Route Leg</th>
                <th className="w-28">Status</th>
                <th className="w-44 text-right">Duty Verification Actions</th>
              </tr>
            </thead>
            <tbody>
              {pendingSubmissions.length > 0 ? (
                pendingSubmissions.map((sub) => (
                  <tr key={sub.id}>
                    <td className="font-mono font-bold text-[#003366] dark:text-blue-300 text-xs">
                      {sub.coach_no} / #{sub.seat_number}
                    </td>
                    <td className="font-semibold text-slate-900 dark:text-slate-100">
                      {sub.passenger_name}
                    </td>
                    <td className="font-mono text-slate-700 dark:text-slate-300 text-xs">
                      {sub.pnr_number}
                    </td>
                    <td className="text-xs text-slate-600 dark:text-slate-400">
                      {sub.journey_from} &rarr; {sub.journey_to}
                    </td>
                    <td>
                      <span className="px-2 py-0.5 rounded-xs text-[10px] font-bold uppercase border bg-amber-50 text-amber-800 border-amber-300 dark:bg-amber-950/60 dark:text-amber-300">
                        {sub.verification_state}
                      </span>
                    </td>
                    <td className="text-right space-x-1.5 whitespace-nowrap">
                      <button
                        onClick={() => handleVerifySubmission(sub.id)}
                        className="px-2.5 py-1 bg-emerald-600 hover:bg-emerald-700 text-white font-bold text-[11px] rounded-xs cursor-pointer transition shadow-2xs inline-flex items-center gap-1"
                        title="Confirm Physical Presence"
                      >
                        <CheckCircle2 className="w-3.5 h-3.5" />
                        <span>Verify</span>
                      </button>
                      <button
                        onClick={() => handleRejectSubmission(sub.id)}
                        className="px-2.5 py-1 bg-rose-50 hover:bg-rose-100 text-rose-800 border border-rose-300 dark:bg-rose-950/60 dark:text-rose-300 font-bold text-[11px] rounded-xs cursor-pointer transition inline-flex items-center gap-1"
                        title="Flag Discrepancy or Absence"
                      >
                        <XCircle className="w-3.5 h-3.5 text-rose-600" />
                        <span>Reject</span>
                      </button>
                    </td>
                  </tr>
                ))
              ) : (
                <tr>
                  <td colSpan={6} className="py-6 text-center text-xs text-slate-500">
                    No pending self-reported passenger check-ins for Train #{selectedTrain?.number}.
                  </td>
                </tr>
              )}
            </tbody>
          </table>
        </div>
      </div>

    </div>
  );
};
